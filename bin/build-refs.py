#!/usr/bin/env python3
"""Generate skill reference files from docs/ and the repo root (single source of truth).

Each skill ships the core sections it needs as references/*.md, so the skill works after the
Claude→Codex sync copies it away from this repository. Never edit generated references by hand:
edit docs/core.md and rerun. `--check` exits 1 when any generated file is stale (used by doctor/CI).
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CORE = ROOT / "docs" / "core.md"
CONTRACT = ROOT / "docs" / "contract.md"

# target file -> list of (source file, section heading prefix or None for the whole file)
PLAN: dict[str, list[tuple[Path, str | None]]] = {
    "skills/artel/references/core-rules.md": [
        (CORE, "## 2. Principles"), (CORE, "## 3. Glossary"), (CORE, "## 4. Project profiles"),
        (CORE, "## 5. Risk tiers"), (CORE, "## 7. Owner gates"), (CORE, "## 8. Roles and models"),
        (CORE, "## 10. Protection"), (CORE, "## 11. Documentation"),
    ],
    "skills/artel-onboard/references/route-o.md": [(CORE, "### 6.6 Route O")],
    "skills/artel-new/references/route-a.md": [(CORE, "### 6.2 Route A")],
    "skills/artel-change/references/route-b.md": [(CORE, "### 6.3 Route B")],
    "skills/artel-incident/references/route-i.md": [(CORE, "### 6.4 Route I")],
    "skills/artel-audit/references/audit.md": [(CORE, "### 6.5 Audit variant")],
    "skills/artel-testing/references/testing-policy.md": [(CORE, "## 9. Testing policy")],
    "skills/artel-doctor/references/contract.md": [(CONTRACT, "## Required capabilities"),
                                                    (CONTRACT, "## Optional capabilities"),
                                                    (CONTRACT, "## Degradation rules"),
                                                    (CONTRACT, "## `artel doctor`")],
    "skills/artel-doctor/references/github.md": [(ROOT / "docs" / "adapters" / "github.md", None)],
    "skills/artel-change/references/orca.md": [(ROOT / "docs" / "adapters" / "orca.md", None)],
    "skills/artel-new/references/release-types.md": [(CONTRACT, "## Release types")],
    "skills/artel-init/references/artel.toml.example": [(ROOT / "artel.toml.example", None)],
}

HEADER = ("<!-- GENERATED by bin/build-refs.py from {src} — do not edit; edit the source and rerun. -->\n"
          "<!-- artel {version} -->\n\n")


def section(text: str, heading: str | None) -> str:
    if heading is None:
        return text.rstrip() + "\n"
    lines = text.splitlines()
    start = next((i for i, l in enumerate(lines) if l.startswith(heading)), None)
    if start is None:
        raise SystemExit(f"section not found: {heading!r}")
    level = len(heading) - len(heading.lstrip("#"))
    end = len(lines)
    for j in range(start + 1, len(lines)):
        m = re.match(r"^(#+) ", lines[j])
        if m and len(m.group(1)) <= level:
            end = j
            break
    return "\n".join(lines[start:end]).rstrip() + "\n"


def version() -> str:
    m = re.search(r"^Version: ([0-9][^ ]*)", CORE.read_text(encoding="utf-8"), re.M)
    return m.group(1) if m else "unknown"


def render(target: str, parts: list[tuple[Path, str | None]]) -> str:
    srcs = sorted({p.relative_to(ROOT).as_posix() for p, _ in parts})
    body = "\n".join(section(p.read_text(encoding="utf-8"), h) for p, h in parts)
    header = HEADER.format(src=", ".join(srcs), version=version())
    if not target.endswith(".md"):  # comment syntax of TOML/YAML/shell
        header = "".join("# " + l[5:-4] + "\n" if l.startswith("<!--") else l + "\n" for l in header.splitlines())
    return header + body


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    for target, parts in PLAN.items():
        path = ROOT / target
        content = render(target, parts)
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(target)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote {target}")
    if check:
        for s in stale:
            print(f"stale: {s}")
        return 1 if stale else 0
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
